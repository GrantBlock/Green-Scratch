/** Writes the routes table into spec/api-contract.md between the markers, from the code in src/api.ts. */
import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import { API_BASE, allRoutes } from '../src/index.ts';
import type { RouteDef } from '../src/index.ts';

const FILE = new URL('../../../spec/api-contract.md', import.meta.url);
const START = '<!-- routes:start (generated by packages/contract: npm run docs) -->';
const END = '<!-- routes:end -->';

function fields(schema?: z.ZodType): string {
  if (!schema) return '';
  const s = schema as unknown as { shape?: Record<string, z.ZodType>; _def?: { innerType?: z.ZodType; in?: z.ZodType } };
  const inner = s.shape ? s : (s._def?.in as typeof s | undefined);
  const shape = inner?.shape;
  if (!shape) return 'see schema';
  const keys = Object.keys(shape).filter((k) => !['version'].includes(k));
  if (keys.length > 8) return `${keys.slice(0, 8).join(', ')}, and ${keys.length - 8} more`;
  return keys.map((k) => (shape[k]!.safeParse(undefined).success ? `${k}?` : k)).join(', ');
}

const rows = (list: RouteDef[]) => list.map((r) => {
  const path = r.audience === 'vault' ? `${API_BASE}${r.path}` : r.path;
  return `| ${r.method} | \`${path}\` | ${r.summary} | ${fields(r.input)} |`;
});

const all = allRoutes();
const vaultActions = all.filter((r) => r.audience === 'vault' && !/^[a-z-]+\.(list|get|create|update)$/.test(r.name));
const crud = all.filter((r) => r.audience === 'vault' && /^[a-z-]+\.(list|get|create|update)$/.test(r.name));
const hub = all.filter((r) => r.audience !== 'vault');
const head = '| Method | Path | What it does | Body or query |\n|---|---|---|---|';

const body = [
  START, '',
  '### Vault actions and queries', '', head, ...rows(vaultActions), '',
  '### Hub routes (public)', '', head, ...rows(hub), '',
  `### Record routes (${crud.length})`, '',
  'Every record type has list and get; most have create and update. Records are archived, never deleted.', '', head, ...rows(crud), '',
  END,
].join('\n');

const current = readFileSync(FILE, 'utf8');
const a = current.indexOf(START), b = current.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers not found in spec/api-contract.md');
writeFileSync(FILE, current.slice(0, a) + body + current.slice(b + END.length));
console.log(`Wrote ${all.length} routes to spec/api-contract.md`);
