/** Writes the fixtures as plain JSON (one file per record type) for people and tools that do not use TypeScript. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fixtures, FIXTURE_TODAY } from '../fixtures/data.ts';

const dir = new URL('../fixtures/json/', import.meta.url);
mkdirSync(dir, { recursive: true });
for (const [name, rows] of Object.entries(fixtures)) writeFileSync(new URL(`${name}.json`, dir), JSON.stringify(rows, null, 2) + '\n');
writeFileSync(new URL('_meta.json', dir), JSON.stringify({ today: FIXTURE_TODAY, note: 'Generated by npm run fixtures:json. Edit fixtures/data.ts instead.' }, null, 2) + '\n');
console.log(`Wrote ${Object.keys(fixtures).length} fixture files`);
